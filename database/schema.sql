CREATE EXTENSION IF NOT EXISTS btree_gist;   -- cần cho exclusion constraint

-- ------------------------------------------------------------
-- ENUM / chỉ cho phép thuộc một tập giá trị cố định
-- ------------------------------------------------------------
CREATE TYPE user_role           AS ENUM ('owner', 'officer');
CREATE TYPE officer_type        AS ENUM ('registration', 'violation');
CREATE TYPE owner_kind          AS ENUM ('individual', 'organization');
CREATE TYPE vehicle_usage       AS ENUM ('personal', 'commercial');
CREATE TYPE registration_status AS ENUM ('active', 'closed', 'revoked', 'cancelled');
CREATE TYPE inspection_result   AS ENUM ('passed', 'failed');
CREATE TYPE detection_source    AS ENUM ('camera', 'on_site');
CREATE TYPE violation_status    AS ENUM ('new', 'verified', 'notified', 'paid', 'appealing', 'cancelled');
CREATE TYPE payment_method      AS ENUM ('online_qr', 'cash');
CREATE TYPE payment_status      AS ENUM ('success', 'failed');
CREATE TYPE appeal_status       AS ENUM ('pending', 'accepted', 'rejected');

-- ------------------------------------------------------------
-- NHÓM 1: NGƯỜI DÙNG VÀ DANH MỤC
-- ------------------------------------------------------------
CREATE TABLE users (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role          user_role     NOT NULL,
    officer_type  officer_type,
    username      VARCHAR(50)   NOT NULL UNIQUE,
    password_hash VARCHAR(255)  NOT NULL,
    full_name     VARCHAR(150)  NOT NULL,
    email         VARCHAR(150)  NOT NULL UNIQUE,
    phone         VARCHAR(20),
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP     NOT NULL DEFAULT now(),
    -- cán bộ bắt buộc có loại cán bộ; chủ xe thì không
    CONSTRAINT ck_users_officer_type
        CHECK ((role = 'officer') = (officer_type IS NOT NULL))
);

CREATE TABLE vehicle_types (
    id                      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    VARCHAR(30)   NOT NULL UNIQUE,
    name                    VARCHAR(100)  NOT NULL,
    usage                   vehicle_usage NOT NULL,
    max_service_years       INT,          -- NULL = không giới hạn niên hạn
    inspection_cycle_months INT           NOT NULL,
    description             TEXT,
    CONSTRAINT ck_vehicle_types_service_years
        CHECK (max_service_years IS NULL OR max_service_years > 0),
    CONSTRAINT ck_vehicle_types_cycle
        CHECK (inspection_cycle_months > 0)
);

CREATE TABLE vehicle_models (
    id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand VARCHAR(60) NOT NULL,
    name  VARCHAR(60) NOT NULL,
    CONSTRAINT uq_vehicle_models_brand_name 
        UNIQUE (brand, name) # 2 dòng khác nhau brand hoặc name hoặc cả 2
);

CREATE TABLE violation_types (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)      NOT NULL UNIQUE,
    name        VARCHAR(255)     NOT NULL,
    detection   detection_source NOT NULL,
    min_fine    NUMERIC(12,0)    NOT NULL,
    max_fine    NUMERIC(12,0)    NOT NULL,
    points      INT              NOT NULL DEFAULT 0,
    description TEXT,
    CONSTRAINT ck_violation_types_min_fine CHECK (min_fine >= 0),
    CONSTRAINT ck_violation_types_max_fine CHECK (max_fine >= min_fine),
    CONSTRAINT ck_violation_types_points   CHECK (points >= 0)
);

CREATE TABLE cameras (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(30)  NOT NULL UNIQUE,
    location_name VARCHAR(255) NOT NULL,
    route         VARCHAR(150) NOT NULL,
    district      VARCHAR(100) NOT NULL,
    latitude      NUMERIC(9,6),
    longitude     NUMERIC(9,6),
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_cameras_latitude  CHECK (latitude  IS NULL OR latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_cameras_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

-- ------------------------------------------------------------
-- NHÓM 2: PHƯƠNG TIỆN VÀ CHỦ SỞ HỮU
-- ------------------------------------------------------------
CREATE TABLE owners (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INT          UNIQUE REFERENCES users(id) ON DELETE SET NULL,
    kind          owner_kind   NOT NULL DEFAULT 'individual',
    full_name     VARCHAR(150) NOT NULL,
    identity_no   VARCHAR(20)  NOT NULL UNIQUE,   -- CCCD hoặc mã số thuế
    date_of_birth DATE,
    phone         VARCHAR(20),
    email         VARCHAR(150),
    address       VARCHAR(255),
    created_at    TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE vehicles (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id         INT         NOT NULL REFERENCES vehicle_models(id),
    vehicle_type_id  INT         NOT NULL REFERENCES vehicle_types(id),
    chassis_no       VARCHAR(30) NOT NULL UNIQUE,
    engine_no        VARCHAR(30) NOT NULL UNIQUE,
    color            VARCHAR(30),
    manufacture_year INT         NOT NULL,
    created_at       TIMESTAMP   NOT NULL DEFAULT now(),
    -- khoảng cố định (không dùng now() trong CHECK); kiểm tra chặt hơn ở backend
    CONSTRAINT ck_vehicles_manufacture_year CHECK (manufacture_year BETWEEN 1980 AND 2100)
);

CREATE TABLE registrations (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id    INT                 NOT NULL REFERENCES vehicles(id),
    owner_id      INT                 NOT NULL REFERENCES owners(id),
    registered_by INT                 NOT NULL REFERENCES users(id),
    plate_number  VARCHAR(15)         NOT NULL,
    valid_from    DATE                NOT NULL,
    valid_to      DATE,               -- NULL = đang hiện hành
    status        registration_status NOT NULL DEFAULT 'active',
    created_at    TIMESTAMP           NOT NULL DEFAULT now(),
    CONSTRAINT ck_registrations_period
        CHECK (valid_to IS NULL OR valid_to > valid_from),
    -- đăng ký hiện hành khi và chỉ khi chưa có ngày kết thúc
    CONSTRAINT ck_registrations_active_open
        CHECK ((status = 'active') = (valid_to IS NULL)),
    -- không chồng lấn thời gian sở hữu của cùng một xe
    CONSTRAINT ex_registrations_no_overlap
        EXCLUDE USING gist (
            vehicle_id WITH =,
            daterange(valid_from, valid_to, '[)') WITH &&
        )
);

-- một xe một đăng ký hiện hành; một biển số một đăng ký hiện hành
CREATE UNIQUE INDEX uq_registrations_active_vehicle
    ON registrations (vehicle_id)   WHERE status = 'active';
CREATE UNIQUE INDEX uq_registrations_active_plate
    ON registrations (plate_number) WHERE status = 'active';

-- ------------------------------------------------------------
-- NHÓM 3: ĐĂNG KIỂM (quy tắc hỗ trợ)
-- ------------------------------------------------------------
CREATE TABLE inspections (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id     INT               NOT NULL REFERENCES vehicles(id),
    inspector_id   INT               NOT NULL REFERENCES users(id),
    result         inspection_result NOT NULL,
    certificate_no VARCHAR(30)       UNIQUE,
    inspected_at   DATE              NOT NULL,
    expires_at     DATE,
    notes          TEXT,
    CONSTRAINT ck_inspections_expiry_after
        CHECK (expires_at IS NULL OR expires_at > inspected_at),
    -- đạt thì có hạn kế tiếp, không đạt thì không
    CONSTRAINT ck_inspections_passed_expiry
        CHECK ((result = 'passed') = (expires_at IS NOT NULL))
);

-- ------------------------------------------------------------
-- NHÓM 4: VI PHẠM VÀ XỬ LÝ
-- ------------------------------------------------------------
CREATE TABLE violations (
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source            detection_source NOT NULL,
    camera_id         INT              REFERENCES cameras(id),
    violation_type_id INT              NOT NULL REFERENCES violation_types(id),
    vehicle_id        INT              REFERENCES vehicles(id),
    registration_id   INT              REFERENCES registrations(id),
    plate_detected    VARCHAR(15)      NOT NULL,
    occurred_at       TIMESTAMP        NOT NULL,
    location_detail   VARCHAR(255),
    fine_amount       NUMERIC(12,0)    NOT NULL,
    status            violation_status NOT NULL DEFAULT 'new',
    evidence_url      VARCHAR(500),
    verified_by       INT              REFERENCES users(id),
    verified_at       TIMESTAMP,
    notified_at       TIMESTAMP,
    due_date          DATE,
    created_at        TIMESTAMP        NOT NULL DEFAULT now(),
    CONSTRAINT ck_violations_fine_positive CHECK (fine_amount > 0),
    -- vi phạm camera phải có camera; vi phạm tại chỗ thì không
    CONSTRAINT ck_violations_source_camera
        CHECK ((source = 'camera') = (camera_id IS NOT NULL)),
    CONSTRAINT ck_violations_due_date
        CHECK (due_date IS NULL OR due_date >= occurred_at::date)
);
-- Chuyển trạng thái đúng luồng và khung mức phạt: trigger trong database/triggers/

CREATE TABLE payments (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_id    INT            NOT NULL REFERENCES violations(id),
    paid_by         INT            REFERENCES owners(id),
    recorded_by     INT            REFERENCES users(id),
    amount          NUMERIC(12,0)  NOT NULL,
    method          payment_method NOT NULL,
    status          payment_status NOT NULL DEFAULT 'success',
    transaction_ref VARCHAR(60)    UNIQUE,
    paid_at         TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    -- nộp online do chủ xe; thu tiền mặt do cán bộ ghi nhận
    CONSTRAINT ck_payments_actor CHECK (
        (method = 'online_qr' AND paid_by IS NOT NULL) OR
        (method = 'cash'      AND recorded_by IS NOT NULL)
    )
);

-- mỗi vi phạm chỉ có một lần nộp thành công (chống nộp trùng)
CREATE UNIQUE INDEX uq_payments_one_success_per_violation
    ON payments (violation_id) WHERE status = 'success';

CREATE TABLE appeals (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_id    INT           NOT NULL REFERENCES violations(id),
    owner_id        INT           NOT NULL REFERENCES owners(id),
    reason          TEXT          NOT NULL,
    status          appeal_status NOT NULL DEFAULT 'pending',
    resolved_by     INT           REFERENCES users(id),
    resolution_note TEXT,
    created_at      TIMESTAMP     NOT NULL DEFAULT now(),
    resolved_at     TIMESTAMP,
    CONSTRAINT ck_appeals_resolved_after
        CHECK (resolved_at IS NULL OR resolved_at >= created_at),
    -- còn chờ xử lý khi và chỉ khi chưa có ngày xử lý
    CONSTRAINT ck_appeals_pending_open
        CHECK ((status = 'pending') = (resolved_at IS NULL))
);

-- mỗi vi phạm chỉ có một khiếu nại đang chờ
CREATE UNIQUE INDEX uq_appeals_one_pending_per_violation
    ON appeals (violation_id) WHERE status = 'pending';

-- ------------------------------------------------------------
-- Chỉ mục cho khóa ngoại thường dùng khi JOIN (không phải 2 chỉ mục hiệu năng của đề)
-- ------------------------------------------------------------
CREATE INDEX idx_registrations_owner   ON registrations (owner_id);
CREATE INDEX idx_vehicles_model        ON vehicles (model_id);
CREATE INDEX idx_vehicles_type         ON vehicles (vehicle_type_id);
CREATE INDEX idx_appeals_violation     ON appeals (violation_id);
CREATE INDEX idx_appeals_owner         ON appeals (owner_id);
